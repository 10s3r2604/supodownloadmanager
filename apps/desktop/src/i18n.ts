export type Language = "en" | "vi";

export function resolveLanguage(setting: string | undefined): Language {
  if (setting === "en" || setting === "vi") return setting;
  return navigator.language.toLowerCase().startsWith("vi") ? "vi" : "en";
}

export type Translate = (key: TextKey, vars?: Record<string, string | number>) => string;

export function translator(language: Language): Translate {
  const texts = language === "vi" ? vi : en;
  return (key, vars) =>
    texts[key].replace(/\{(\w+)\}/g, (match, name: string) =>
      vars && name in vars ? String(vars[name]) : match,
    );
}
